    await page.getByRole('tab', { name: /120 mm/ }).click();
    await expect(page.getByRole('textbox', { name: 'Sträckans bredd' })).toHaveValue('');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Ta bort alternativ' }).click();
