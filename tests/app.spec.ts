test('calculates corners and preserves valid input through offline reload', async ({ page, context }) => {
    await page.goto('./');
    await expect(page.getByRole('heading', { name: 'Din vägg' })).toBeVisible();
    await page.getByRole('button', { name: '13,6 m med knutar' }).click();
    await expect(page.getByRole('img', { name: /Fasad med 68 bottenbrädor och 67 lock/ })).toBeVisible();
    await expect(page.locator('.detail-metrics')).toContainText('13 490,0');
    await page.getByRole('button', { name: 'Botten 1', exact: true }).click();
    await expect(page.locator('.selection')).toContainText('55,0');
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
    await page.evaluate(async () => {
        await navigator.serviceWorker.ready;
        if (!navigator.serviceWorker.controller)
            await new Promise<void>(resolve => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }));
    });
    const manifest = await page.request.get('manifest.webmanifest');
    expect(manifest.ok()).toBeTruthy();
    expect((await manifest.json()).scope).toBe('/panel_kalkylator/');
    await context.setOffline(true);
    await page.reload();
    await expect(page.getByRole('img', { name: /Fasad med 68 bottenbrädor/ })).toBeVisible();
    await context.setOffline(false);
});
